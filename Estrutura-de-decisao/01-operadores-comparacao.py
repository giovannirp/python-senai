# Verifica se os números são diferentes
print("numero1 != numero2: ", numero1 != numero2)

# Verifica se numero1 é menor que o numero2
print("numero1 < numero2: ", numero1 < numero2)

# Verifica se numero1 é menor ou igual a numero2
print("numero1 <= numero2: ", numero1 <= numero2)

# Verifica se o numero1 é maior que numero2
print("numero1 > numero2: ", numero1 > numero2)

# Verifica se numero1 é maior ou igual a numero2
