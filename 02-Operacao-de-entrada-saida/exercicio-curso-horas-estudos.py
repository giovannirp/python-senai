
# Faça um programa que peça o nome de um curso
# e a quantidade de horas que o aluno estuda nesse curso.
# Depois, mostre essas informações no terminal.

# Entrada de dados
curso = input("Digite o nome do curso: ")
horas = int(input("Digite a quantidade de horas do curso: "))

# Processamento computacional
horas_estudos = horas

# Saída de informações
print(f"Curso: {curso}")
print(f"Quantidade de horas: {horas_estudos} horas")


